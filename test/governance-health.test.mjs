import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { buildArtifacts, defaultConfig } from '../src/generator.mjs';
import { applyArtifactPlan, planArtifacts } from '../src/managed-files.mjs';
import { scanProject } from '../src/scanner.mjs';
import { checkProject } from '../src/checker.mjs';

function fixture(context, name) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), `aicg-health-${name}-`));
  context.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const scan = scanProject(root);
  const config = { ...defaultConfig(scan), clients: ['codex'], stacks: ['generic-unknown'] };
  applyArtifactPlan(root, planArtifacts(root, buildArtifacts(config, scan)));
  return root;
}

test('check exposes one honest health summary and actionable next steps', (context) => {
  const root = fixture(context, 'summary');
  const result = checkProject(scanProject(root));

  assert.equal(result.ok, true, result.errors.join('\n'));
  assert.equal(result.health.overall, 'attention');
  assert.equal(result.health.stages.bootstrap, 'generated');
  assert.equal(result.health.stages.structure, 'pass');
  assert.equal(result.health.stages.reachability, 'pass');
  assert.equal(result.health.stages.clients, 'unverified');
  assert.ok(result.health.nextActions.some((entry) => entry.id === 'record-real-client-replay'));
  assert.equal(result.repair.status, 'not-needed');
  assert.deepEqual(result.repair.candidates, []);
});

test('orphan repair preview classifies generated candidates separately from owner review', (context) => {
  const root = fixture(context, 'orphans');
  const generated = 'docs/ai/development/legacy-generated.md';
  const owner = 'docs/ai/development/owner-notes.md';
  fs.mkdirSync(path.dirname(path.join(root, generated)), { recursive: true });
  fs.writeFileSync(path.join(root, generated), '<!-- Generated by AI Code Governance -->\nLegacy generated guidance.\n');
  fs.writeFileSync(path.join(root, owner), '# Owner notes\nDo not replace automatically.\n');

  const result = checkProject(scanProject(root));

  assert.equal(result.ok, true, result.errors.join('\n'));
  assert.equal(result.repair.status, 'review-required');
  assert.equal(result.repair.mutatesRepository, false);
  assert.equal(result.repair.previewCommand, 'aicg sync . --prune --dry-run');
  assert.deepEqual(result.repair.candidates, [
    { path: generated, classification: 'historical-generated-review' },
    { path: owner, classification: 'owner-review-required' },
  ]);
  assert.ok(result.health.nextActions.some((entry) => entry.id === 'review-governance-orphans'
    && entry.command === 'aicg sync . --prune --dry-run'));
});
